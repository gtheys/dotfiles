-- AIDEV-NOTE: transparent bg for any colorscheme (dms/base46 sets its own bg even
-- with matugenTemplateNeovimSetBackground=false in DMS settings.json)
vim.api.nvim_create_autocmd("ColorScheme", {
  callback = function()
    for _, grp in ipairs({ "Normal", "NormalNC", "NormalFloat", "EndOfBuffer" }) do
      vim.api.nvim_set_hl(0, grp, { bg = "NONE" })
    end
    -- AIDEV-NOTE: dms theme leaves snacks explorer groups linked to NonText (near-black),
    -- making dotfiles and git-untracked/ignored entries invisible on dark backgrounds
    vim.api.nvim_set_hl(0, "SnacksPickerPathHidden", { link = "Special" })
    vim.api.nvim_set_hl(0, "SnacksPickerPathIgnored", { link = "Special" })
    vim.api.nvim_set_hl(0, "SnacksPickerGitStatusUntracked", { link = "Special" })
    vim.api.nvim_set_hl(0, "SnacksPickerGitStatusIgnored", { link = "Special" })
  end,
})

return {
  -- AIDEV-NOTE: Set tokyonight-storm as the default LazyVim colorscheme
  -- lazy=false and priority ensure it loads before other plugins
  -- on_highlights clears Normal bg for terminal transparency
  {
    "folke/tokyonight.nvim",
    lazy = false,
    priority = 1000,
    opts = {
      style = "storm",
      transparent = true,
      styles = {
        sidebars = "transparent",
        floats = "transparent",
      },
      on_highlights = function(hl, c)
        hl.Normal = { fg = c.fg, bg = "NONE" }
        hl.NormalFloat = { fg = c.fg, bg = "NONE" }
      end,
    },
  },
  -- AIDEV-NOTE: dms colorscheme needs AvengeMedia/base46; theme files
  -- (~/.config/nvim/colors/dms.lua) are generated by `dms matugen generate`
  {
    "AvengeMedia/base46",
    lazy = true,
    opts = {},
  },
  {
    "LazyVim/LazyVim",
    opts = {
      colorscheme = "dms",
    },
  },
}
